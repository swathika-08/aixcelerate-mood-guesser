def count_moods(data):
  happy_count=0
  sad_count=0
  for i in data:
    if i[1].upper() == "HAPPY":
      happy_count+=1
    elif i[1].upper() == "SAD":
      sad_count+=1
  return happy_count,sad_count

happy_words=["Glad","Excited","Great","pleased","Thrilled","Cheerful","Grateful","Content","proud","Wonderful"]
sad_words=["upset","failed","Disappointed","Hurt","Lonely","Miserable","Heartbroken","lost","Unfortunate","Sorry"]

def guess_mood(sentence):
  hc=0
  sc=0
  a=sentence.lower()
  for word in happy_words:
    if word.lower() in a:
      hc+=1
  for word in sad_words:
    if word.lower() in a:
      sc+=1
  if hc>sc:
    return "HAPPY"
  elif sc>hc:
    return "SAD"
  else:
    return "HAPPY"

